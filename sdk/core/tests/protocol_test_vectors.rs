//! Canonical test vectors for Gate 3 — CBOR and signature golden values.
//!
//! These vectors pin the exact byte output of the canonical CBOR encoder and the
//! Ed25519 signer for a fixed, deterministic input. Any change to the encoding,
//! the domain separator, the field ordering, or the signing algorithm that
//! alters these bytes is a **breaking protocol change** and requires:
//!
//! 1. An ADR update (ADR-008 for CBOR, ADR-002 for crypto)
//! 2. Change-control review (`.agent/CHANGE_CONTROL.md`)
//! 3. Update to ALL dependent test vectors and simulation data
//!
//! # Vector input
//!
//! All inputs are fully deterministic:
//! - UUIDs: fixed byte sequences
//! - Nonce: `[0x01; 16]`
//! - Timestamps: fixed integers
//! - Amount: 150 (INR paise = ₹1.50)
//! - Counter: 1
//! - Signing key: `Ed25519TestSigner::from_seed([0x42; 32])`
//!
//! # How to update vectors
//!
//! 1. Run with `REGENERATE_VECTORS=1 cargo test test_vectors -- --nocapture`
//! 2. Copy the printed hex values into the expected constants below
//! 3. Confirm the change through change-control before committing
//!
//! This file deliberately does NOT auto-update — the freeze is intentional.

use resilientpay_core::{
    crypto::{sign_envelope, Ed25519TestSigner, Signer},
    envelope::EnvelopeBuilder,
    money::Money,
    serialization::{encode_envelope_cbor, signing_input},
    types::{CredentialId, KeyId, MerchantId, TransactionId},
    PROTOCOL_VERSION,
};
use uuid::Uuid;

// ---------------------------------------------------------------------------
// Fixed vector inputs (all deterministic)
// ---------------------------------------------------------------------------

const VECTOR_TX_UUID: &str = "00000000-0000-0000-0000-000000000001";
const VECTOR_CR_UUID: &str = "00000000-0000-0000-0000-000000000002";
const VECTOR_KEY_UUID: &str = "00000000-0000-0000-0000-000000000003";
const VECTOR_MER_UUID: &str = "00000000-0000-0000-0000-000000000004";
const VECTOR_NONCE: [u8; 16] = [0x01u8; 16];
const VECTOR_AMOUNT: u64 = 150; // 150 paise = ₹1.50
const VECTOR_COUNTER: u64 = 1;
const VECTOR_CREATED: i64 = 1_700_000_000;
const VECTOR_EXPIRES: i64 = 1_700_003_600;
const VECTOR_SEED: [u8; 32] = [0x42u8; 32];

fn vector_envelope() -> resilientpay_core::PaymentEnvelopeCore {
    EnvelopeBuilder::new()
        .protocol_version(PROTOCOL_VERSION)
        .tx_id(TransactionId::from_uuid(
            Uuid::parse_str(VECTOR_TX_UUID).unwrap(),
        ))
        .credential_id(CredentialId::from_uuid(
            Uuid::parse_str(VECTOR_CR_UUID).unwrap(),
        ))
        .payer_key_id(KeyId::from_uuid(Uuid::parse_str(VECTOR_KEY_UUID).unwrap()))
        .merchant_id(MerchantId::from_uuid(
            Uuid::parse_str(VECTOR_MER_UUID).unwrap(),
        ))
        .amount(Money::new(VECTOR_AMOUNT, "INR").unwrap())
        .counter(VECTOR_COUNTER)
        .nonce(VECTOR_NONCE)
        .created_at_unix_secs(VECTOR_CREATED)
        .expires_at_unix_secs(VECTOR_EXPIRES)
        .build()
        .unwrap()
}

